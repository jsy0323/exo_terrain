    @property
    def pelvis_heading(self) -> np.ndarray:
        """
        Cached horizontal forward heading (world frame), shape (3,), float32.
        """
        sc = self.step_count
        if sc != self._pelvis_heading_step:
            self._rebuild_pelvis_heading_cache()
            self._pelvis_heading_step = sc
        return self._pelvis_heading_cache
    
    def _rebuild_pelvis_heading_cache(self) -> None:
        """
        Horizontal forward heading of the pelvis in world frame.

        Returns
        -------
        heading : np.ndarray, shape=(3,), float32
            Unit vector in world coordinates representing the pelvis heading.

        Notes
        -----
        - World coordinate axes:
          X: forward (anterior), Y: leftward, Z: upward.
        - The pelvis local frame at initialization aligns its X-axis
          with the world X-axis, Z-axis with the world Z-axis, and
          Y-axis with the world Y-axis.
        - This method ignores any tilt (rotation about Z) and list
          (rotation about X) to extract only the yaw rotation.
        """
        try:
            bid = self._pelvis_bid
        except AttributeError:
            bid = self.model.body('pelvis').id
            self._pelvis_bid = bid
    
        row = self.data.xmat[bid]
        hx, hy = float(row[0]), float(row[3])
        n = hx*hx + hy*hy
    
        v = self._pelvis_heading_cache  # float32(3,)
        if n < 1e-8:        # EPS
            v[0], v[1], v[2] = 1.0, 0.0, 0.0
            return
    
        inv = 1.0 / np.sqrt(n)
        v[0] = np.float32(hx * inv)
        v[1] = np.float32(hy * inv)
        v[2] = np.float32(0.0)
        
    @property
    def R_world_to_local_pelvis(self) -> np.ndarray:
        """
        Cached rotation (world→pelvis-local). 每个 step_count 只重建一次。
        """
        sc = self.step_count
        if sc != self._Rw2l_cache_step:
            self._rebuild_Rw2l_cache()
            self._Rw2l_cache_step = sc
        return self._Rw2l_cache
    
    def _rebuild_Rw2l_cache(self) -> None:
        """
        Rotation (world → pelvis-local “forward-left-up” frame), shape (3,3), float32.
        Columns of the local frame are:
          x = pelvis_heading (forward, horizontal),
          z = world up = [0,0,1],
          y = z × x (left).
        We return R^T (world→local) directly for faster downstream matvec: rel = R @ delta.
        """
        x = self.pelvis_heading
        y0 = -x[1]
        y1 =  x[0]
        ny2 = y0*y0 + y1*y1
    
        if ny2 < 1e-6:
            x0p, x1p, x2p = 1.0, 0.0, 0.0
            y0,  y1       = 0.0, 1.0
        else:
            inv = 1.0 / np.sqrt(ny2)
            y0 *= inv; y1 *= inv
            x0p =  y1
            x1p = -y0
            x2p =  0.0
    
        R = self._Rw2l_cache  # float32 (3,3)
        R[0, 0] = np.float32(x0p); R[0, 1] = np.float32(x1p); R[0, 2] = x2p
        R[1, 0] = np.float32(y0);  R[1, 1] = np.float32(y1);  R[1, 2] = 0.0
        R[2, 0] = 0.0;             R[2, 1] = 0.0;             R[2, 2] = 1.0

    def close(self) -> None:
        """Close renderers and clean up resources."""
        self.logger.debug("Closing environment")
        for name in ("comp_trim", "short_history", "long_history"):
            if hasattr(self, name):
                setattr(self, name, None)
        
        acc = getattr(self, "traj_manager", None)
        if isinstance(acc, _ShmTrajectoryAccessor):
            acc.close()
                
        super().close()
        self.logger.debug("Environment closed successfully")
        
