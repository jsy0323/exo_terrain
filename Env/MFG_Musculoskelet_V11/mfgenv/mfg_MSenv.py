    def _upload_terrain_hfield_visual(self) -> None:
        """Best-effort refresh of hfield GPU resources for active renderers."""
        try:
            import mujoco

            hid = mujoco.mj_name2id(
                self.model,
                mujoco.mjtObj.mjOBJ_HFIELD,
                self.terrain_hfield_name,
            )
            if hid < 0:
                return

            viewer = getattr(self, "viewer", None)
            update_hfield = getattr(viewer, "update_hfield", None)
            if callable(update_hfield):
                update_hfield(hid)
                return

            contexts = []
            for owner in (
                getattr(self, "renderer", None),
                viewer,
                getattr(viewer, "_sim_renderer", None),
                getattr(viewer, "_renderer", None),
            ):
                if owner is None:
                    continue
                for attr in ("_mjr_context", "_mjr_ctx", "_context", "context"):
                    ctx = getattr(owner, attr, None)
                    if ctx is not None:
                        contexts.append(ctx)

            for ctx in contexts:
                try:
                    mujoco.mjr_uploadHField(self.model, ctx, hid)
                except Exception:
                    pass
        except Exception:
            pass

    def _get_anchor_world(self) -> np.ndarray:
        """
        Choose the anchor (in world coordinates) based on the current phase.
    
        Returns
        -------
        p_anchor_world : Optional[np.ndarray], shape (3,), dtype float64
            - IMITATION: reference pelvis position mapped to world by your convention:
                [ref[2], -ref[0], ref[1] + pelvis_z_offset]
            - REACH_GOAL: current goal position if available
            - None: when no valid anchor is available (e.g., no goal yet). In this case,
              the caller should treat relative position as [0, 0, 0] without extra queries.
    
        Notes
        -----
        - This helper does NOT touch MuJoCo data or call `get_state(self)`.
          It is safe and cheap to call every step.
        """
        # IMITATION: use reference pelvis as anchor
        if (self.phase is EnvPhase.IMITATION) and (not self.ref_traj.has_reached_end):
            z_off = float(getattr(self, "pelvis_z_offset", 0.95))
            ref_qpos = np.asarray(self.ref_traj.get_qpos(), dtype=np.float64, order="C")
            return np.array([ref_qpos[2], -ref_qpos[0], ref_qpos[1] + z_off], dtype=np.float64)
    
        # REACH_GOAL: use goal if available; otherwise no anchor (None)
        g = getattr(self, "goal_pos", None)
        if g is None:
            return None
        return np.asarray(g, dtype=np.float64, order="C")
        
    def _get_obs(self) -> Tuple[np.ndarray, dict]:
        """
        Assemble the environment observation vector and auxiliary components.
    
        The returned observation is packed into a preallocated buffer `self._obs_buf` as:
          [ progress,              # scalar in [0, 1] if frames > 0 else 0
            is_periodic,           # 1.0 if the reference clip is periodic, else 0.0
            phase_sin,             # smooth sinusoidal encoding of the gait phase
            phase_cos,             # smooth cosine encoding of the gait phase
            base_state... ]        # flattened features from `get_state(self)`
    
        Parameters
        ----------
        self : object
            Environment instance providing:
              - ref_traj : object with attributes `_pos`, `traj_frames`, and optional `phase`
              - observation_space : gym.Space to validate observations against
              - _obs_buf : preallocated np.ndarray (float32, C-contiguous)
              - validate_obs : bool, whether to check bounds with `observation_space.contains`
              - return_obs_copy : bool, if True returns a copy of the buffer
    
        Returns
        -------
        obs : np.ndarray, float32
            The packed observation buffer. If `return_obs_copy` is True, a copy is returned;
            otherwise the internal buffer `self._obs_buf` is returned.
        components : dict
            Auxiliary dictionaries produced by `get_state(self)` (e.g., current and
            reference kinematic components) for debugging or logging.
    
        Notes
        -----
        - Ensures `base_state` is float32 and C-contiguous before copying into `_obs_buf`.
        - Phase encoding avoids the 1→0 discontinuity for periodic clips and remains
          smooth for non-periodic clips by reusing the global progress angle.
        - Raises `ValueError` if `validate_obs` is True and the observation is out of bounds.
        """
        ref_traj    = self.ref_traj
        validate    = self.validate_obs
        obs_space   = self.observation_space
        return_copy = getattr(self, "return_obs_copy", False)
        
        # ---- progress / phase encoding ----
        pos     = float(ref_traj._pos)
        frames  = float(ref_traj.traj_frames)
        progress = (pos / frames) if frames > 0.0 else 0.0

        periodic = bool(getattr(ref_traj, "periodic", False))
        if periodic:
            raw_phase = float(getattr(ref_traj, "phase", 0.0)) * 0.01
            theta = float(raw_phase) * (2.0 * math.pi)
            phase_sin = math.sin(theta)
            phase_cos = math.cos(theta)
        else:
            # non-periodic clip: reuse progress but without wrap-around
            theta = float(progress) * math.pi
            phase_sin = math.sin(theta)
            phase_cos = math.cos(theta)
        
        # ---- base_state from external module ----
        base_state, components = get_state(self, include_orient_angvel=self.include_orient_angvel)
        if not (isinstance(base_state, np.ndarray)
                and base_state.dtype == np.float32
                and base_state.flags.c_contiguous):
            base_state = np.asarray(base_state, dtype=np.float32, order="C")
        
        obs_buf = self._obs_buf
    
        obs_buf0 = obs_buf
        obs_buf0[0] = np.float32(progress)
        obs_buf0[1] = np.float32(1.0 if periodic else 0.0)
        obs_buf0[2] = np.float32(phase_sin)
        obs_buf0[3] = np.float32(phase_cos)

        obs_buf0[self._obs_base_slice] = base_state

        muscle_slice = self._obs_muscle_slice
        if muscle_slice.stop > muscle_slice.start:
            if self._has_muscle_actuators:
                obs_buf0[muscle_slice] = self.data.act[self.muscle_indices]
            else:
                obs_buf0[muscle_slice] = self._muscle_zero_buf

        terrain_slice = self._obs_terrain_slice
        if terrain_slice.stop > terrain_slice.start:
            obs_buf0[terrain_slice] = self._get_terrain_obs()
    
        if validate and (not obs_space.contains(obs_buf)):
            raise ValueError(f"Observation out of bounds for {obs_space}")
    
        return (obs_buf.copy() if return_copy else obs_buf), components

    def _update_frame_skip(self) -> None:
        """
        Recompute self.frame_skip from the current trajectory settings.
    
        - Avoids work if nothing relevant changed (same result as before).
        - Clamps to a sane range and ensures Python int.
        - Optionally precomputes derived timing for quick access.
        """
        # calculate_frameskip will raise if something is invalid
        new_fs = int(calculate_frameskip(self))
        
        if new_fs < 1:
            # Be strict but safe; never allow <1
            self.logger.warning("calculate_frameskip() returned %d; clamped to 1.", new_fs)
            new_fs = 1
        
        old_fs = getattr(self, "frame_skip", None)
        if old_fs == new_fs:
            return
        
        self.logger.debug("Frame skip changed from %s → %d", str(old_fs), new_fs)
        self.frame_skip = new_fs
        
        self.dt_env = float(self.model.opt.timestep) * float(self.frame_skip)
    
    def _update_traj_init_info(self) -> None:
        """
        Prepare initial qpos/qvel from the reference trajectory.
        
        - Zero-alloc fast path: avoid extra copies if arrays are already float64 & C-contiguous.
        - Validates shapes against model.nq / model.nv.
        - Ensures we own the buffers (no aliasing into TrajectoryManager storage).
        """
        if not hasattr(self, "ref_traj") or self.ref_traj is None:
            raise ValueError("Reference trajectory object is not initialized.")

        ref_qpos, ref_qvel = self.ref_traj.get_reference_trajectories()
        if ref_qpos is None or ref_qvel is None:
            raise ValueError("Failed to retrieve reference trajectories from ref_traj.")
        
        init_qpos = convert_ref_traj_qpos(ref_qpos)
        init_qvel = convert_ref_traj_qvel(ref_qvel, ref_qpos)
        init_qpos, init_qvel = self.human_state_map.expand(init_qpos, init_qvel)
        
        nq, nv = int(self.model.nq), int(self.model.nv)
        if init_qpos is None or init_qvel is None:
            raise ValueError("Conversion from reference trajectories returned None.")
        if init_qpos.shape != (nq,):
            raise ValueError(f"init_qpos shape {init_qpos.shape} != (nq,)={(nq,)}")
        if init_qvel.shape != (nv,):
            raise ValueError(f"init_qvel shape {init_qvel.shape} != (nv,)={(nv,)}")
        
        init_qpos = np.require(init_qpos, dtype=np.float64, requirements=("C",))
        init_qvel = np.require(init_qvel, dtype=np.float64, requirements=("C",))
        
        self._init_qpos = init_qpos.copy()
        self._init_qvel = init_qvel.copy()
        
    def _prewarm_pelvis_local_caches_from_init(self) -> None:
        """
        Warmstart the pelvis heading and rotation matrix using the quaternion from _init_qpos.
        """
        if not getattr(self, "relative_pelvis", False):
            if not hasattr(self, "_Rw2l_cache"):
                self._Rw2l_cache = np.eye(3, dtype=np.float32)
            else:
                self._Rw2l_cache[:] = np.eye(3, dtype=np.float32)
            if not hasattr(self, "_pelvis_heading_cache"):
                self._pelvis_heading_cache = np.array([1.0, 0.0, 0.0], dtype=np.float32)
            else:
                self._pelvis_heading_cache[:] = (1.0, 0.0, 0.0)
            self._pelvis_heading_step = self.step_count
            self._Rw2l_cache_step     = self.step_count
            return
        q = np.asarray(self._init_qpos, dtype=np.float64)
        qw_qx_qy_qz = q[3:7]
        Rw = quat_to_mat(qw_qx_qy_qz)
        
        xaxis = Rw[:, 0]
        hx, hy = float(xaxis[0]), float(xaxis[1])
        n = hx*hx + hy*hy
        if not hasattr(self, "_pelvis_heading_cache"):
            self._pelvis_heading_cache = np.zeros(3, dtype=np.float32)
        v = self._pelvis_heading_cache
        if n < 1e-8:
            v[0], v[1], v[2] = 1.0, 0.0, 0.0
        else:
            inv = 1.0 / np.sqrt(n)
            v[0] = np.float32(hx * inv)
            v[1] = np.float32(hy * inv)
            v[2] = np.float32(0.0)
        self._pelvis_heading_step = self.step_count 
        
        if not hasattr(self, "_Rw2l_cache"):
            self._Rw2l_cache = np.empty((3,3), dtype=np.float32)
        R = self._Rw2l_cache
        y0 = -v[1]; y1 = v[0]
        ny2 = float(y0*y0 + y1*y1)
        if ny2 < 1e-6:
            x0p, x1p, x2p = 1.0, 0.0, 0.0
            y0,  y1       = 0.0, 1.0
        else:
            inv = 1.0 / np.sqrt(ny2)
            y0 *= inv; y1 *= inv
            x0p =  y1; x1p = -y0; x2p = 0.0
        R[0, 0] = np.float32(x0p); R[0, 1] = np.float32(x1p); R[0, 2] = x2p
        R[1, 0] = np.float32(y0);  R[1, 1] = np.float32(y1);  R[1, 2] = 0.0
        R[2, 0] = 0.0;             R[2, 1] = 0.0;             R[2, 2] = 1.0
        self._Rw2l_cache_step = self.step_count
        
    def reset(
        self,
        *,
        seed: Optional[int] = None,
        traj_id: Optional[int] = None,
        frame: Optional[int] = None,
        options: Optional[Dict[str, Any]] = None
        ) -> Tuple[np.ndarray, Dict[str, Any]]:
        """Reset environment state, reference cursor, phase, frame_skip, and history.

        This override does the following in addition to MuJoCoEnv.reset():
          1. Reset the ReferenceTrajectories cursor to a (possibly new) trajectory.
          2. Reset the FSM phase back to IMITATION.
          3. Clear step counter, goal position, and next‐goal timer.
          4. Recompute frame_skip to match the new trajectory parameters.
          5. Reinitialize history buffers if 'enable_history' is True.
          6. Populate 'info' with traj_id, progress, phase, and empty histories.

        Parameters
        ----------
        seed : Optional[int]
            Random seed to pass through to the base reset.
        options : Optional[Dict[str, Any]]
            Additional options for the base reset (unused here).

        Returns
        -------
        obs : np.ndarray
            Initial observation after reset, as returned by '_get_obs()'.
        info : Dict[str, Any]
            Diagnostic info including:
              - 'traj_id'      : int
              - 'progress'     : float, initial progress (0.0)
              - 'phase'        : str, 'IMITATION'
              - 'short_history': list (empty if enabled)
              - 'long_history' : list (empty if enabled)
        """
        self.step_count = 0
        self._pelvis_heading_step = -1
        self._Rw2l_cache_step     = -1
        
        if seed is not None:
            self._seed(seed)
        
        self.ref_traj.reset(
            seed=seed,
            phase=None,
            randomize_traj=(traj_id is None),
            traj_id=traj_id
            )
        
        if frame is not None:
            # clamp to [0, traj_frames-1]
            tf = int(self.ref_traj.traj_frames)
            f  = int(frame)
            if tf <= 0:
                f = 0
            else:
                if f < 0:        f = 0
                elif f >= tf:    f = tf - 1
            self.ref_traj._pos = f
            self.ref_traj._has_reached_end = (f >= tf - 1) if tf > 0 else True

        self._randomize_terrain_on_reset()
        
        self._update_traj_init_info()
        
        self._prewarm_pelvis_local_caches_from_init()
        
        obs, info = super().reset(options=options)

        if self._jerk_prev1.size:
            self._jerk_prev1.fill(0.0)
            self._jerk_prev2.fill(0.0)
            self._jerk_buf.fill(0.0)
        self._jerk_have_prev = 0

        self.phase = EnvPhase.IMITATION
        self.goal_pos = self.DEFAULT_GOAL_POS.copy()
        self._next_goal_update = 0.0

        # Clear history if enabled
        if self.enable_history:
            self._init_history_buffers()
            info["short_history"] = []
            info["long_history"]  = []

        tf = float(self.ref_traj.traj_frames)
        pos = float(self.ref_traj._pos)
        progress = (pos / tf) if tf > 0.0 else 0.0
    
        info.update({
            "traj_id": self.ref_traj.traj_id,
            "progress": progress,
            "phase": self.phase.name,
        })
        if self.num_critic_extra_obs:
            info['critic_extra_obs'] = self.human_state_map.interface_state(self.data)
    
        self.logger.debug("Environment reset complete: traj_id=%s, frame=%s, fs=%d",
                          info["traj_id"], int(pos), int(self.frame_skip))
        return obs, info
    
    def _clip_action(self, act_raw):
        """Map policy outputs into actuator bounds with muscle-aware handling."""
        a = np.asarray(act_raw, dtype=np.float32)
        if a.ndim != 1:
            a = a.reshape(-1)
        if a.size != self.num_actuators:
            raise ValueError(f"action size mismatch: got {a.size}, expected {self.num_actuators}")

        out = a.copy()
        collect_stats = bool(self.log_clip_stats)
        stats = {} if collect_stats else None
        k=2
        muscle_idx = getattr(self, "muscle_indices", None)
        if isinstance(muscle_idx, np.ndarray) and muscle_idx.size > 0:
            low_m = self._ctrl_low[muscle_idx]
            span_m = self._ctrl_high[muscle_idx] - low_m
            out[muscle_idx] = low_m + span_m * (0.5 * (np.tanh(k*out[muscle_idx]) + 1.0))
            if collect_stats:
                band = out[muscle_idx]
                stats["muscle_ctrl_min"] = float(band.min())
                stats["muscle_ctrl_max"] = float(band.max())

        pos_idx = getattr(self, "position_indices", None)
        if isinstance(pos_idx, np.ndarray) and pos_idx.size > 0:
            low_p = self._ctrl_low[pos_idx]
            high_p = self._ctrl_high[pos_idx]
            center = 0.5 * (high_p + low_p)
            span = 0.5 * (high_p - low_p)
            out[pos_idx] = center + span * np.tanh(k*out[pos_idx])
            if collect_stats:
                band = out[pos_idx]
                stats["position_ctrl_min"] = float(band.min())
                stats["position_ctrl_max"] = float(band.max())

        np.clip(out, self._ctrl_low, self._ctrl_high, out=out)
        return out, stats
    
    def step(
        self,
        action: np.ndarray
        ) -> Tuple[np.ndarray, float, bool, bool, Dict[str, Any]]:
        """
        Advance one time-step, then compute reward/termination with minimal
        extra work by reusing components collected in the base env.
    
        Pipeline:
          1) physics + obs + sim-side components  -> super().step(action)
          2) advance reference cursor             -> self.ref_traj.next()
          3) FSM update (IMITATION -> REACH_GOAL) / goal refresh
          4) prepare light-weight 'comp_trim' for reward/termination
             - reuse sim-side comps from info['obs_components']
             - add ref-side comps if phase requires (cheap path)
          5) compute reward & termination
          6) finalize info (avoid big copies unless explicitly requested)

        Parameters
        ----------
        action : np.ndarray, shape=(num_actuators,)
            Control inputs for each actuator.

        Returns
        -------
        obs : np.ndarray
            Next observation as built by '_get_obs()'.
        reward : float
            Scalar task reward combining all terms.
        terminated : bool
            True if a terminal condition (e.g., fall) is met.
        truncated : bool
            True if the episode is truncated (e.g., ref_traj finished or max steps reached).
        info : dict
            Diagnostics, including per-term reward breakdown and termination details.
        """
        self.ref_traj.next()
        self.step_count += 1
        sim_time = self.step_count * self.opt_time * self.frame_skip
        
        clip_stats = None
        if self._do_clip_action:
            action, clip_stats = self._clip_action(action)
        obs, _, _, _, info = super().step(action)

        self._update_joint_jerk_buffers()
        
        comps = info.get("obs_components", None)
        if comps is None:
            raise KeyError("info must contain key 'obs_components' provided by base env.")
        
        # FSM transition: IMITATION → REACH_GOAL
        if self.enable_reach_goal:
            if (self.phase is EnvPhase.IMITATION and self.ref_traj.has_reached_end):
                self.phase = EnvPhase.REACH_GOAL
                self._next_goal_update = sim_time + self.goal_switch_interval
            if (self.phase is EnvPhase.REACH_GOAL and sim_time >= self._next_goal_update):
                self.goal_pos = self._sample_goal_position()
                self._next_goal_update += self.goal_switch_interval
            
        if self.enable_reach_goal and (self.phase is EnvPhase.REACH_GOAL):
            comps["goal_pos"] = self.goal_pos
        
        total_reward, reward_info = compute_reward(self, comps)
        # print(reward_info)
        if not self.log_reward_breakdown:
            reward_info = None
        terminated, term_info = check_termination(self, comps, ["has_fallen", "site_deviation_exceeded"])
        interface_travel = self.human_state_map.travel_fraction(self.data.qpos)
        # End slipped/detached episodes before the emergency stops become a
        # persistent rigid force path that a policy could exploit.
        term_info['interface_slip'] = not np.isfinite(interface_travel) or interface_travel >= .8
        terminated = terminated or term_info['interface_slip']
        info['interface_travel_fraction'] = interface_travel
        
        at_max = (self.step_count >= self.max_episode_steps)
        if self.enable_reach_goal:
            truncated = at_max
        else:
            truncated = self.ref_traj.has_reached_end or at_max

        if self.enable_history:
            self._update_history_buffer(action, obs)
            
        # Build info dict
        info.update({
            "terminated_info": term_info,
            "phase": self.phase.name,
            "traj_id": self.ref_traj.traj_id,
            "progress": float(self.ref_traj._pos) / float(self.ref_traj.traj_frames),
        })
        if self.num_critic_extra_obs:
            info['critic_extra_obs'] = self.human_state_map.interface_state(self.data)
        if self.log_reward_breakdown and reward_info is not None:
            info["reward_info"] = reward_info
        if self.log_clip_stats and clip_stats is not None:
            info["clip_stats"] = clip_stats
        
        if self.enable_history:
            info["short_history"] = list(self.short_history)
            info["long_history"]  = list(self.long_history)

        self.logger.debug(
            "Step %d | reward=%.4f | term=%s | trunc=%s | phase=%s",
            self.step_count, float(total_reward), bool(terminated), bool(truncated), self.phase.name
        )

        return obs, float(total_reward), bool(terminated), bool(truncated), info
    
