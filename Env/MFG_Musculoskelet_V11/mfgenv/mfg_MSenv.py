class _ShmTrajectoryAccessor:
    """
    Shared-memory backed proxy that mirrors :class:`TrajectoryManager` for worker
    processes.  It reconstructs NumPy views from metadata generated by
    ``build_traj_shm_meta`` so that child processes can reuse trajectories
    without duplicating arrays in memory.

    Parameters
    ----------
    meta_list : Sequence[Mapping[str, Any]]
        Per-trajectory descriptors containing shared-memory handles and
        statistics (speed, periodicity, cycle length, etc.).
    sample_frequency : float
        Sampling rate of the stored trajectories in hertz.
    jnt_map : Mapping[str, int]
        Joint-name to index mapping to preserve the manager API.

    Notes
    -----
    - Array payloads are never copied; ``get()`` returns read-only views mapped
      onto the shared-memory buffers.
    - The accessor exposes the same interrogation methods as
      :class:`TrajectoryManager`, allowing environment code to remain agnostic
      to whether it receives a real manager instance or this lightweight proxy.
    """

    def __init__(self, meta_list, sample_frequency: float, jnt_map: dict):
        self.sample_frequency = float(sample_frequency)
        self.jnt_name = dict(jnt_map)
        self._qpos_shm = {}
        self._qvel_shm = {}
        self._meta = []
        self._speeds = []
        self._foot = []
        self._periodic = []
        self._repeat = []
        self._cycle_frames = []
        self._period_conf = []

        for idx, raw in enumerate(meta_list):
            if not isinstance(raw, dict):
                raise TypeError(f"traj_shm_meta[{idx}] must be dict, got {type(raw)}")

            try:
                q_meta = dict(raw["qpos"])
                v_meta = dict(raw["qvel"])
            except KeyError as exc:
                raise KeyError(f"traj_shm_meta[{idx}] missing {exc.args[0]!r}") from exc

            q_meta["shape"] = tuple(q_meta["shape"])
            v_meta["shape"] = tuple(v_meta["shape"])
            q_meta["dtype"] = str(q_meta["dtype"])
            v_meta["dtype"] = str(v_meta["dtype"])

            traj_frames = int(q_meta["shape"][1]) if len(q_meta["shape"]) > 1 else 1

            speed = float(raw.get("speed", 0.0))
            foot = int(raw.get("foot", 0))
            periodic = bool(raw.get("periodic", raw.get("is_periodic", False)))
            repeat = int(raw.get("repeat_count", raw.get("repeat", 1)))
            cycle = int(raw.get("cycle_frames", raw.get("cycle", raw.get("step_frames", traj_frames))))
            confidence = float(raw.get("periodicity_confidence", raw.get("confidence", 0.0)))

            if repeat <= 0:
                repeat = 1
            if cycle <= 0:
                cycle = traj_frames if traj_frames > 0 else 1

            self._meta.append({"qpos": q_meta, "qvel": v_meta})
            self._speeds.append(speed)
            self._foot.append(foot)
            self._periodic.append(periodic)
            self._repeat.append(repeat)
            self._cycle_frames.append(cycle)
            self._period_conf.append(confidence)

    def length(self) -> int:
        return len(self._meta)

    def get(self, traj_id: int):
        m = self._meta[traj_id]
        # qpos
        q_meta = m["qpos"]
        name, shape, dtype = q_meta["name"], tuple(q_meta["shape"]), np.dtype(q_meta["dtype"])
        shm = self._qpos_shm.get(name)
        if shm is None:
            shm = shared_memory.SharedMemory(name=name)
            self._qpos_shm[name] = shm
        qpos = np.ndarray(shape, dtype=dtype, buffer=shm.buf)
        qpos.setflags(write=False)
        # qvel
        v_meta = m["qvel"]
        name, shape, dtype = v_meta["name"], tuple(v_meta["shape"]), np.dtype(v_meta["dtype"])
        shm = self._qvel_shm.get(name)
        if shm is None:
            shm = shared_memory.SharedMemory(name=name)
            self._qvel_shm[name] = shm
        qvel = np.ndarray(shape, dtype=dtype, buffer=shm.buf)
        qvel.setflags(write=False)
        return qpos, qvel

    def get_speed(self, traj_id: int) -> float:
        return float(self._speeds[traj_id])

    def get_foot_start(self, traj_id: int) -> int:
        return int(self._foot[traj_id])

    def is_periodic(self, traj_id: int) -> bool:
        return bool(self._periodic[traj_id])

    def get_repeat_count(self, traj_id: int) -> int:
        return int(self._repeat[traj_id])

    def get_cycle_frames(self, traj_id: int) -> int:
        return int(self._cycle_frames[traj_id])

    def get_periodicity_confidence(self, traj_id: int) -> float:
        return float(self._period_conf[traj_id])

    def get_jnt_map(self) -> dict:
        return dict(self.jnt_name)

    def get_sample_frequency(self) -> float:
        return self.sample_frequency

    def close(self):
        for d in (self._qpos_shm, self._qvel_shm):
            for shm in d.values():
                try:
                    shm.close()
                except Exception:
                    pass
        self._qpos_shm.clear()
        self._qvel_shm.clear()


class MFG_Musculoskeletal_V11(MuJoCoEnv):
    """
    Version 11 musculoskeletal environment with optional reach-goal phase.

    Notes
    -----
    * Built on :class:`MuJoCoEnv`; the physics model and actuator metadata are
      cached in the parent class, so instantiating multiple MSenv instances in
      parallel workers avoids repeated XML parsing.
    * Class-level constants gather immutable configuration (required reward
      keys, default visual markers, buffer templates) to reduce per-instance
      allocations and keep initialisation time low.
    * Diagnostic payloads (reward breakdown, clip statistics, history buffers)
      are fully optional. Disabling them minimises cross-process traffic and
      per-step Python object churn during large-scale training.
    """

    # Immutable configuration -----------------------------------------------------------------
    REQUIRED_REWARD_KEYS = MappingProxyType({"imitation": 1, "smooth": 1, "goal": 1})
    REQUIRED_IMM_WEIGHTS = MappingProxyType(
        {"site_pos": 1, "site_vel": 1, "joint_angle": 1, "joint_angvel": 1}
    )
    REQUIRED_SMOOTH_WEIGHTS = MappingProxyType({"energy": 1, "synergy": 1, "jerk": 1})
    REQUIRED_REWARD_COEFFS = MappingProxyType(
        {
            "site_pos": 1,
            "site_vel": 1,
            "joint_angle": 1,
            "joint_angvel": 1,
        }
    )

    DEFAULT_GOAL_SWITCH_INTERVAL = 1.0
    DEFAULT_MAX_EPISODE_STEPS = 1000
    DEFAULT_HISTORY_SHORT = 5
    DEFAULT_HISTORY_LONG = 30
    DEFAULT_MUSCLE_OBS_DIM = 80  # fallback when the model has no muscle actuators

    DEFAULT_GOAL_POS = np.zeros(3, dtype=np.float32)
    DEFAULT_GOAL_POS.setflags(write=False)
    DEFAULT_PELVIS_HEADING = np.array([1.0, 0.0, 0.0], dtype=np.float32)
    DEFAULT_PELVIS_HEADING.setflags(write=False)
    DEFAULT_RW2L = np.eye(3, dtype=np.float32)
    DEFAULT_RW2L.setflags(write=False)
    
    def __init__(self, config: Dict[str, Any], render_mode: Optional[str] = None, **kwargs):
        """
        Initialize the MFG_Musculoskeletal_V9 environment.

        Parameters
        ----------
        config : dict
            -- MuJoCoEnv settings   (passed to super()):
                    model_path          (str): XML model file path (required).
                    default_frame_skip  (int): Physics steps per env.step() (>=1).
                    render_mode         (Optional[str]): "human", "rgb_array", or None.
                    timestep            (Optional[float]): Override integrator timestep.
                    camera              (Optional[int|str]): Offscreen camera ID.

            -- traj_manager        (TrajectoryManager):
                    Shared instance for loading and preprocessing reference trajectories.

            -- High‐level reward weights:
               reward_weights      (dict):
                    'imitation'    (float): Weight for entire imitation term.
                    'smooth'       (float): Weight for entire smoothness term.
                    'goal'         (float): Weight for entire reach‐goal term.

            -- Imitation‐term sub‐weights:
               imitation_weights   (dict):
                    'site_pos'     (float),
                    'site_vel'     (float),
                    'Fstepangle'  (float),
                    'joint_angvel' (float).

            -- Smooth‐term sub‐weights:
               smooth_weights      (dict):
                    'energy'       (float),
                    'synergy'      (float),
                    'jerk'         (float).

            -- Per‐term reward coefficients:
               reward_coefficients (dict):
                    'site_pos'     (float),
                    'site_vel'     (float),
                    'joint_angle'  (float),
                    'joint_angvel' (float),

            -- Reach-goal settings:
                    enable_reach_goal   (bool, optional): Enable reach-goal phase. Default False.
                    goal_switch_interval(float, optional): Seconds between goal updates. Default 1.0.


            -- Episode settings:
                    max_episode_steps   (int, optional): Max steps per episode. Default 1000.

            -- Reference‐trajectory cursor:
                    increment            (int, optional): Frames to advance per step (default=1).
                    max_hold_steps       (int, optional): Steps to hold at end of traj before marking done (default=1).
                    traj_seed            (int, optional): Seed for random trajectory selection/phase.
                    rt_verbose           (bool, optional): Whether ReferenceTrajectories prints debug info (default=False).
               
            -- History buffering:
                    enable_history      (bool, optional): Record (action, obs) history. Default False.
                    short_history_max_len(int, optional): Length of short history. Default 5.
                    long_history_max_len (int, optional): Length of long history. Default 30.
        Raises:
            TypeError: If 'config['traj_manager']' is not a TrajectoryManager.
            KeyError:  If any required reward or trajectory keys are missing.
        """
        self.logger = logging.getLogger(f"{__name__}.{self.__class__.__name__}")
        self.logger.debug("Initializing MFG_Musculoskeletal_V11 (MSenv)")
        
        # Base initialization (physics, action_space, base obs_space, rendering, seeding)
        super().__init__(config, render_mode=render_mode, **kwargs)
        if self.render_mode is None:
            self.auto_render = False

        # -------------------------------
        # Shared TrajectoryManager
        # -------------------------------
        from multiprocessing.managers import BaseProxy
        tm = config.get("traj_manager", None)

        meta_list = kwargs.get("traj_shm_meta", None) or config.get("traj_shm_meta", None)
        if meta_list is not None:
            jnt_map = TrajectoryManager.EXPANDED_JOINT_MAP
            sample_freq = float(kwargs.get("traj_sample_frequency", config.get("traj_sample_frequency", 100.0)))
            self.traj_manager = _ShmTrajectoryAccessor(meta_list, sample_freq, jnt_map)
        else:
            if tm is None or not (isinstance(tm, TrajectoryManager) or isinstance(tm, BaseProxy)):
                raise KeyError(
                    "Config must contain either 'traj_shm_meta' (+ 'traj_sample_frequency') "
                    "or a 'traj_manager' (TrajectoryManager instance/proxy)."
                )
            self.traj_manager = tm
        
        # -------------------------------
        # ReferenceTrajectories cursor
        # -------------------------------
        increment = int(config.get("increment", 1))
        max_hold = int(config.get("max_hold_steps", 1))
        rt_seed = config.get("traj_seed", None)
        rt_verbose = bool(config.get("rt_verbose", False))
        self.ref_traj = ReferenceTrajectories(
            manager=self.traj_manager,
            traj_id=None,          # None → choose random trajectory at reset()
            increment=increment,
            max_hold_steps=max_hold,
            random_seed=rt_seed,
            verbose=rt_verbose
        )
        self._update_frame_skip()
        
        # -------------------------------
        # Reward weights and coefficients
        # -------------------------------
        ## High‐level weights for each major term
        rw = config.get("reward_weights", {})
        required_rw_keys = set(self.REQUIRED_REWARD_KEYS.keys())
        missing_rw = required_rw_keys - set(rw.keys())
        if missing_rw:
            raise KeyError(f"Config['reward_weights'] missing keys: {sorted(missing_rw)}")
        self.reward_weights = {k: float(v) for k, v in rw.items()}
        
        ## Sub‐weights for the imitation term
        iw = config.get("imitation_weights", {})
        required_i_keys = set(self.REQUIRED_IMM_WEIGHTS.keys())
        missing_i = required_i_keys - set(iw.keys())
        if missing_i:
            raise KeyError(f"Config['imitation_weights'] missing keys: {sorted(missing_i)}")
        self.imitation_weights = {k: float(v) for k, v in iw.items()}

        ## Sub‐weights for the smoothness term
        sw = config.get("smooth_weights", {})
        required_s_keys = set(self.REQUIRED_SMOOTH_WEIGHTS.keys())
        missing_s = required_s_keys - set(sw.keys())
        if missing_s:
            raise KeyError(f"Config['smooth_weights'] missing keys: {sorted(missing_s)}")
        self.smooth_weights = {k: float(sw[k]) for k in required_s_keys}

        terrain_weight_defaults = {
            "pelvis_height": 0.0,
            "foot_clearance": 0.0,
        }
        tw = config.get("terrain_weights", {}) or {}
        self.terrain_weights = {
            k: float(tw.get(k, default)) for k, default in terrain_weight_defaults.items()
        }
        for k, v in tw.items():
            if k not in self.terrain_weights:
                self.terrain_weights[k] = float(v)

        tr = dict(config.get("terrain_reward", {}) or {})
        tr.setdefault("nominal_pelvis_height", 0.95)
        tr.setdefault("pelvis_height_sigma", 0.12)
        tr.setdefault("foot_clearance_min", 0.10)
        tr.setdefault("foot_clearance_sigma", 0.05)
        tr.setdefault("foot_clearance_swing_only", True)
        tr.setdefault("right_foot_sites", ("toes_r_sensor", "calcn_r_sensor"))
        tr.setdefault("left_foot_sites", ("toes_l_sensor", "calcn_l_sensor"))
        self.terrain_reward = tr

        ar = dict(config.get("alive_reward", {}) or {})
        ar.setdefault("reward", 1.0)
        ar.setdefault("fallen_reward", 0.0)
        ar.setdefault("pelvis_height_range", (0.6, 1.3))
        ar.setdefault("use_terrain_relative_height", False)
        self.alive_reward = ar

        gr = dict(config.get("grf_reward", {}) or {})
        gr.setdefault("max_total_force_bw", 1.6)
        gr.setdefault("max_vertical_force_bw", 1.3)
        gr.setdefault("total_force_weight", 0.5)
        gr.setdefault("vertical_force_weight", 1.0)
        self.grf_reward = gr

        cr = dict(config.get("com_reward", {}) or {})
        cr.setdefault("target_forward_offset", 0.02)
        cr.setdefault("target_lateral_offset", 0.0)
        cr.setdefault("position_forward_sigma", 0.25)
        cr.setdefault("position_lateral_sigma", 0.10)
        cr.setdefault("capture_forward_sigma", 0.35)
        cr.setdefault("capture_lateral_sigma", 0.14)
        cr.setdefault("lateral_velocity_sigma", 0.35)
        cr.setdefault("height_min", 0.65)
        cr.setdefault("height_sigma", 0.15)
        cr.setdefault("position_weight", 0.5)
        cr.setdefault("capture_weight", 1.0)
        cr.setdefault("lateral_velocity_weight", 0.25)
        cr.setdefault("height_weight", 0.0)
        cr.setdefault("right_support_sites", ("toes_r_sensor", "calcn_r_sensor"))
        cr.setdefault("left_support_sites", ("toes_l_sensor", "calcn_l_sensor"))
        self.com_reward = cr

        ur = dict(config.get("upward_reward", {}) or {})
        ur.setdefault("use_sites", True)
        ur.setdefault("start_site", "pelvis_sensor")
        ur.setdefault("end_site", "thorax_sensor")
        ur.setdefault("target_dot", 0.85)
        ur.setdefault("sigma_dot", 0.12)
        ur.setdefault("min_vector_length", 0.05)
        ur.setdefault("body_name", "thorax")
        ur.setdefault("body_axis", (0.0, 0.0, 1.0))
        self.upward_reward = ur

        ## Per‐term reward coefficients
        rc = config.get("reward_coefficients", {})
        required_rc_keys = set(self.REQUIRED_REWARD_COEFFS.keys())
        missing_rc = required_rc_keys - set(rc.keys())
        if missing_rc:
            raise KeyError(f"Config['reward_coefficients'] missing keys: {sorted(missing_rc)}")
        self.reward_coefficients = {k: float(v) for k, v in rc.items()}
        self.enable_site_orn = bool(
            float(self.imitation_weights.get("site_orn", self.reward_coefficients.get("site_orn", 0.0))) != 0.0
        )
        self.enable_site_angvel = bool(
            float(self.imitation_weights.get("site_angvel", self.reward_coefficients.get("site_angvel", 0.0))) != 0.0
        )
        self.log_reward_breakdown = bool(config.get("log_reward_breakdown", False))
        self.log_clip_stats = bool(config.get("log_clip_stats", False))

        # -------------------------------
        # Reach‐goal FSM settings
        # -------------------------------
        self.enable_reach_goal = bool(config.get("enable_reach_goal", False))
        self.phase = EnvPhase.IMITATION
        self.goal_switch_interval = float(config.get("goal_switch_interval", self.DEFAULT_GOAL_SWITCH_INTERVAL))
        self.goal_pos = self.DEFAULT_GOAL_POS.copy()
        self._next_goal_update = 0.0  # simulation time (s) to next goal recalculation
        
        # -------------------------------
        # Internal state flags & counters
        # -------------------------------
        self.step_count = 0
        self.max_episode_steps = int(config.get("max_episode_steps", self.DEFAULT_MAX_EPISODE_STEPS))
        jerk_dim = max(int(self.human_state_map.qvel_indices.size) - 6, 0)
        self._jerk_prev1 = np.zeros(jerk_dim, dtype=np.float32)
        self._jerk_prev2 = np.zeros(jerk_dim, dtype=np.float32)
        self._jerk_buf = np.zeros(jerk_dim, dtype=np.float32)
        self._jerk_have_prev = 0
        self.relative_pelvis = bool(config.get("relative_pelvis", False))
        self.include_orient_angvel = bool(
            config.get("include_orient_angvel", False) or self.enable_site_orn or self.enable_site_angvel
        )
        self.terrain_hfield_name = str(config.get("terrain_hfield_name", "random_terrain"))
        self.terrain_floor_geom_name = str(config.get("terrain_floor_geom_name", "floor"))
        self.terrain_obs_enabled = bool(config.get("terrain_obs_enabled", False))
        terrain_grid_shape = config.get("terrain_grid_shape", None)
        if terrain_grid_shape is not None:
            rows, cols = (int(v) for v in terrain_grid_shape)
            if rows <= 0 or cols <= 0:
                raise ValueError(f"terrain_grid_shape must be positive, got {terrain_grid_shape}")
            x_range = tuple(float(v) for v in config.get("terrain_grid_x_range", (0.0, 3.0)))
            y_range = tuple(float(v) for v in config.get("terrain_grid_y_range", (-1.0, 1.0)))
            if len(x_range) != 2 or len(y_range) != 2:
                raise ValueError("terrain_grid_x_range and terrain_grid_y_range must contain two values")
            self.terrain_grid_x = tuple(np.linspace(x_range[0], x_range[1], cols, dtype=np.float32))
            self.terrain_grid_y = tuple(np.linspace(y_range[0], y_range[1], rows, dtype=np.float32))
        else:
            self.terrain_grid_x = tuple(float(v) for v in config.get("terrain_grid_x", []))
            self.terrain_grid_y = tuple(float(v) for v in config.get("terrain_grid_y", []))
        if self.terrain_obs_enabled and (not self.terrain_grid_x or not self.terrain_grid_y):
            self.terrain_grid_x = tuple(np.linspace(0.0, 2.0, 9, dtype=np.float32))
            self.terrain_grid_y = tuple(np.linspace(-0.8, 0.8, 9, dtype=np.float32))
        self.terrain_randomize_on_reset = bool(config.get("terrain_randomize_on_reset", False))
        self.terrain_random_height_scale = config.get("terrain_random_height_scale", None)
        self.terrain_random_height_scale = (
            None if self.terrain_random_height_scale is None else float(self.terrain_random_height_scale)
        )
        self.terrain_random_smooth_passes = int(config.get("terrain_random_smooth_passes", 8))
        self.terrain_flat_start_length = float(config.get("terrain_flat_start_length", 2.0))
        self.terrain_flat_transition_length = float(config.get("terrain_flat_transition_length", 1.0))
        self.terrain_flat_start_height = float(config.get("terrain_flat_start_height", 0.0))
        self.terrain_mode = str(config.get("terrain_mode", "random"))
        if self.terrain_mode not in {"random", "structured"}:
            raise ValueError(f"Unsupported terrain_mode: {self.terrain_mode}")
        from .terrain import normalize_structured_kinds

        structured_kinds_cfg = config.get("terrain_structured_kinds", config.get("terrain_structured_kind", None))
        self.terrain_structured_kinds = normalize_structured_kinds(structured_kinds_cfg)
        self.terrain_structured_segment_length_range = tuple(
            float(v) for v in config.get("terrain_structured_segment_length_range", (1.0, 3.0))
        )
        self.terrain_structured_slope_range_deg = tuple(
            float(v) for v in config.get("terrain_structured_slope_range_deg", (3.0, 8.0))
        )
        self.terrain_structured_step_height_range = tuple(
            float(v) for v in config.get("terrain_structured_step_height_range", (0.03, 0.08))
        )
        self.terrain_structured_step_run_range = tuple(
            float(v) for v in config.get("terrain_structured_step_run_range", (0.3, 0.6))
        )
        self.terrain_structured_roughness_range = tuple(
            float(v) for v in config.get("terrain_structured_roughness_range", (0.01, 0.04))
        )
        terrain_seed = config.get("terrain_random_seed", None)
        if terrain_seed is None:
            terrain_seed = int(
                np.random.SeedSequence([os.getpid() & 0xFFFFFFFF, id(self) & 0xFFFFFFFF]).generate_state(1)[0]
            )
        self._terrain_rng = np.random.default_rng(terrain_seed)
        
        self._pelvis_heading_cache = self.DEFAULT_PELVIS_HEADING.copy()
        self._pelvis_heading_step  = -1
        self._Rw2l_cache = self.DEFAULT_RW2L.copy()
        self._Rw2l_cache_step = -1
        # -------------------------------
        # History recording toggle
        # -------------------------------
        self.enable_history = bool(config.get("enable_history", False))
        if self.enable_history:
            self.short_history_max_len = int(config.get("short_history_max_len", self.DEFAULT_HISTORY_SHORT))
            self.long_history_max_len  = int(config.get("long_history_max_len", self.DEFAULT_HISTORY_LONG))
            self._init_history_buffers()
            self.logger.debug(
                "History enabled: short_max=%d, long_max=%d",
                self.short_history_max_len, self.long_history_max_len
            )
        else:
            self.short_history = None
            self.long_history  = None

        # -------------------------------
        # Observation_space
        # -------------------------------
        base_dim = get_state_size(self, include_orient_angvel=self.include_orient_angvel)

        muscle_idx = getattr(self, "muscle_indices", None)
        if isinstance(muscle_idx, np.ndarray) and muscle_idx.size > 0:
            self._has_muscle_actuators = True
            muscle_obs_dim = int(muscle_idx.size)
        else:
            self._has_muscle_actuators = False
            muscle_obs_dim = self.DEFAULT_MUSCLE_OBS_DIM
        
        # muscle_obs_dim = 0
        self._obs_base_dim = base_dim
        self._obs_muscle_dim = muscle_obs_dim
        self._obs_terrain_dim = (
            len(self.terrain_grid_x) * len(self.terrain_grid_y)
            if self.terrain_obs_enabled
            else 0
        )
        self._obs_dim = base_dim + muscle_obs_dim + self._obs_terrain_dim + 4
        obs_low   = np.full(self._obs_dim, -np.inf, dtype=np.float32)
        obs_high  = np.full(self._obs_dim, +np.inf, dtype=np.float32)
        if muscle_obs_dim > 0:
            start = 4 + base_dim
            end = start + muscle_obs_dim
            obs_low[start:end] = 0.0
            obs_high[start:end] = 1.0
        self.observation_space = spaces.Box(low=obs_low, high=obs_high, dtype=np.float32)
        self.num_critic_extra_obs = int(self.human_state_map.interface_state_dim)
        self.num_privileged_obs = self._obs_dim + self.num_critic_extra_obs
        self._obs_buf = np.empty(self._obs_dim, dtype=np.float32)

        # Precompute slices to avoid per-step arithmetic
        self._obs_base_slice = slice(4, 4 + base_dim)
        self._obs_muscle_slice = slice(self._obs_base_slice.stop, self._obs_base_slice.stop + muscle_obs_dim)
        self._obs_terrain_slice = slice(
            self._obs_muscle_slice.stop,
            self._obs_muscle_slice.stop + self._obs_terrain_dim,
        )
        if self._has_muscle_actuators:
            self._muscle_zero_buf = None
        else:
            self._muscle_zero_buf = np.zeros(muscle_obs_dim, dtype=np.float32)
        self._terrain_zero_buf = np.zeros(self._obs_terrain_dim, dtype=np.float32)
        
        self.logger.debug("MSenv initiallization finished.")
        
    @property
    def observation_dim(self) -> int:
        """Total flattened observation dimension."""
        return self._obs_dim
    
    def _init_history_buffers(self) -> None:
        """Create (or clear) deques for short and long history of (action, obs)."""
        sh = getattr(self, "short_history", None)
        if sh is None or sh.maxlen != self.short_history_max_len:
            self.short_history = deque(maxlen=self.short_history_max_len)
        else:
            sh.clear()

        lh = getattr(self, "long_history", None)
        if lh is None or lh.maxlen != self.long_history_max_len:
            self.long_history = deque(maxlen=self.long_history_max_len)
        else:
            lh.clear()

        required_len = int(self.num_actuators + self._obs_dim)
        tmp = getattr(self, "_hist_tmp", None)
        if tmp is None or tmp.size != required_len:
            self._hist_tmp = np.empty(required_len, dtype=np.float32)
        else:
            self._hist_tmp.fill(0.0)
        self._hist_item_len = required_len
        
    def _update_history_buffer(self, action: np.ndarray, obs: np.ndarray) -> None:
        """Append the concatenated (action, obs) to history deques."""
        buf = self._hist_tmp
        na  = self.num_actuators
        
        buf[:na] = action
        buf[na:na+obs.size] = obs
        item = buf.copy()
        self.short_history.append(item)
        if self.long_history is not self.short_history:
            self.long_history.append(item)

    def _update_joint_jerk_buffers(self) -> None:
        """Update cached joint jerk (second position difference) excluding pelvis DOFs."""
        qpos = self.data.qpos
        tail = qpos[self.human_state_map.qpos_indices[7:]]
        have = self._jerk_have_prev
        if have >= 2:
            np.copyto(self._jerk_buf, tail)
            np.subtract(self._jerk_buf, self._jerk_prev1, out=self._jerk_buf)
            np.subtract(self._jerk_buf, self._jerk_prev1, out=self._jerk_buf)
            np.add(self._jerk_buf, self._jerk_prev2, out=self._jerk_buf)
        else:
            self._jerk_buf.fill(0.0)

        if have >= 1:
            np.copyto(self._jerk_prev2, self._jerk_prev1)
        np.copyto(self._jerk_prev1, tail)
        if have < 2:
            self._jerk_have_prev = have + 1

